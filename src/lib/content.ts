/** slug の配列から Capability を並び順どおりに取り出す。 */
export function capabilitiesBySlug(slugs: string[]): Capability[] {
  return slugs
    .map((slug) => capabilities.find((c) => c.slug === slug))
    .filter((c): c is Capability => Boolean(c));
}

