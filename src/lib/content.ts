/* ------------------------------------------------------------------
 * できること（Capabilities）＝ 実際に動くデモを用意した得意領域。
 * トップの一覧カードと /demo 配下の各ページの双方から参照します。
 * ---------------------------------------------------------------- */

export type Capability = {
  /** URL スラッグ（/demo/<slug>） */
  slug: string;
  /** 見出し */
  title: string;
  /** 一覧カード用の短い説明（1行） */
  tagline: string;
  /**
   * カードで太字表示する「事業へのインパクト」1行。
   * 技術の説明ではなく、導入すると会社の何が変わるかを書く。
   */
  impact: string;
  /** 詳細ページ・構造化データ用の説明（3行以内） */
  description: string;
  icon: IconKey;
  /** カードのビジュアル用グラデーション（Tailwind クラス） */
  gradient: string;
  /** 導入すると何が起きるか（企業側のメリット） */
  businessValue: { title: string; body: string }[];
  /** このデモをAIを活用して実装するのに要した時間 */
  buildTime: string;
  /** できることの箇条書き */
  bullets: string[];
  /** 使用技術 */
  tech: string[];
  /** 活用シーン */
  useCases: string[];
  /**
   * デモの範囲と制約（誠実さ＝E-E-A-Tの Trust）。
   * 「どこまでが実装で、本番では何が変わるか」を必ず明示します。
   */
  demoNote: string;
  /** デモの操作説明 */
  howToUse: string[];
  /**
   * 検索されている言葉に寄せた見出し（H1・<title> に使う）。
   * 機能名（例：「AR」）ではなく、検索窓に打ち込まれる言葉（例：「WebAR 制作 費用」）を
   * 主語にすること。15本のデモページを、そのまま15本の検索入口にするための項目です。
   */
  searchTitle: string;
  /** 上の見出しに添える1行（検索意図への即答） */
  searchLead: string;
  /** このページで受ける検索語（keywords と本文の言い回しの基準） */
  searchTerms: string[];
  /**
   * 費用の目安に使うプラン帯（金額そのものは `plans` を単一情報源とする）。
   * ⚠️ ここで新しい金額を作らないこと。実在しない価格を書くと信用を損ないます。
   */
  priceBand: "standard" | "premium";
  /** 金額が動く要因（「費用」で検索した人への即答） */
  costFactors: string[];
  /** 実装期間の目安（実績ではなく目安として表示する） */
  leadTime: string;
};

