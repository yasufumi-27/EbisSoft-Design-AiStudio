import fs from 'node:fs';
import ts from 'typescript';

// The static page receives the same implementation imported by StudioMotion.tsx.
const source = fs.readFileSync('src/lib/studio-motion.ts', 'utf8');
const result = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020, removeComments: true },
});
fs.writeFileSync('public/studio-motion.js', '// Generated by scripts/prepare-studio-motion.mjs. Do not edit.\n' + result.outputText);
